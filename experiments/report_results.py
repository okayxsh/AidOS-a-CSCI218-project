"""Write the report tables for one run as Markdown, straight from its summary.json.

    cd apps/api
    uv run python ../../experiments/report_results.py <run_id> [--out ../../docs/evaluation/results-tables.md]

Every number in the output is copied from summary.json (itself computed from the CSV files),
so the tables cannot drift from the data. Interpretation lives in docs/evaluation/results.md.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
POLICIES = ["fcfs", "greedy", "aidos", "aidos_balanced"]
NAME = {
    "fcfs": "FCFS",
    "greedy": "Urgency greedy",
    "aidos": "AidOS",
    "aidos_balanced": "AidOS balanced",
}
MAIN = [
    "unit_coverage",
    "mean_resource_coverage",
    "urgency_weighted_coverage",
    "critical_coverage",
    "min_zone_coverage",
    "starved_zones",
    "starved_share",
    "coverage_gap",
    "jain_fairness",
    "usable_stock_utilization",
    "runtime_ms",
]


def f(x, digits=3):
    return "N/A" if x is None else f"{x:.{digits}f}"


def p(x):
    if x is None:
        return "N/A"
    return "< 0.0001" if x < 0.0001 else f"{x:.4f}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("run_id")
    parser.add_argument("--results", type=Path, default=ROOT / "experiments" / "results")
    parser.add_argument(
        "--out", type=Path, default=ROOT / "docs" / "evaluation" / "results-tables.md"
    )
    args = parser.parse_args()
    run = args.results / args.run_id
    s = json.loads((run / "summary.json").read_text(encoding="utf-8"))
    m = json.loads((run / "manifest.json").read_text(encoding="utf-8"))
    st = s["static"]
    meta = {x["key"]: x for x in s["metrics"]}
    out: list[str] = []
    w = out.append

    w(f"# Results tables: run `{args.run_id}`\n")
    w(
        f"Generated by `experiments/report_results.py` from `experiments/results/{args.run_id}/summary.json`. "
        "Do not edit by hand; re-run the script. Interpretation: [`results.md`](results.md).\n"
    )
    c = m["counts"]
    w(
        f"- Status **{m['status']}**, {m['duration_s']} s; engine {m['versions']['engine']}, fuzzy rules "
        f"{m['versions']['fuzzy_config']}, OR-Tools {m['versions']['ortools']}, Python {m['versions']['python']}."
    )
    w(
        f"- Static: {c['static_scenarios']} scenarios x 4 policies = {c['static_records']} records "
        f"(families {', '.join(st['families'])}, {c['static_scenarios'] // len(st['families'])} each)."
    )
    w(
        f"- Dynamic: {c['dynamic_scripts']} scripts, {c['dynamic_steps']} recommendation steps; "
        f"{c['dispatch_runs']} dispatch trajectories. Scaling: {c['scaling_records']} timed runs. "
        f"Failures: {c['failures']}."
    )
    b = s["bootstrap"]
    w(
        f"- Confidence intervals: percentile bootstrap, {b['resamples']} resamples, seed {b['seed']}, "
        f"level {b['level']:.0%}. `*` marks objective-aligned metrics.\n"
    )

    w("## 1. Feasibility and solver status\n")
    w("| Policy | Plans returned | Valid plans | Proven optimal | Statuses |")
    w("|---|---|---|---|---|")
    for pol in POLICIES:
        fe = st["feasibility"][pol]
        statuses = ", ".join(f"{k} {v}" for k, v in st["statuses"][pol].items())
        w(
            f"| {NAME[pol]} | {fe['plans']}/{fe['total']} | {fe['valid']}/{fe['total']} | "
            f"{fe['optimal_proven']}/{fe['total']} | {statuses} |"
        )
    w("")
    w("Identical plans (same units to every zone and resource) on the same scenario:\n")
    w("| Pair | Scenarios with identical plans |")
    w("|---|---|")
    for pair, n in st["identical_plans"].items():
        a, bb = pair.split("|")
        w(f"| {NAME[a]} vs {NAME[bb]} | {n} / {st['scenarios']} |")
    w("")

    w("## 2. Static benchmark: mean (sd) per policy, all families\n")
    w("| Metric | Better | " + " | ".join(NAME[x] for x in POLICIES) + " |")
    w("|---|---|" + "---|" * len(POLICIES))
    for key in MAIN:
        mk = meta[key]
        star = "*" if mk["aligned"] else ""
        cells = []
        for pol in POLICIES:
            d = st["overall"][pol][key]
            digits = 2 if key == "runtime_ms" else 3
            cells.append(f"{f(d['mean'], digits)} ({f(d['sd'], digits)})" if d["n"] else "N/A")
        w(f"| {mk['label']}{star} | {mk['better']} | " + " | ".join(cells) + " |")
    n_crit = st["overall"]["aidos"]["critical_coverage"]["n"]
    w(
        f"\nCritical-zone coverage is defined only for scenarios with a zone scoring at least 75 "
        f"({n_crit} of {st['scenarios']}). Runtime is the median of repeated timings per scenario.\n"
    )

    w("## 3. Paired differences (policy minus comparator, same scenarios), all families\n")
    w("| Comparison | Metric | n | Mean diff [95% CI] | Median diff | Wins / ties / losses | d_z |")
    w("|---|---|---|---|---|---|---|")
    order = [
        ("aidos", "fcfs"),
        ("greedy", "fcfs"),
        ("aidos", "greedy"),
        ("aidos_balanced", "aidos"),
        ("aidos_balanced", "fcfs"),
    ]
    keys = [
        "urgency_weighted_coverage",
        "critical_coverage",
        "min_zone_coverage",
        "starved_zones",
        "coverage_gap",
        "jain_fairness",
        "unit_coverage",
    ]
    for a, bb in order:
        for key in keys:
            cmp = next(
                x
                for x in st["comparisons"]
                if (x["scope"], x["a"], x["b"], x["metric"]) == ("all", a, bb, key)
            )
            ci = cmp["ci_mean"]
            w(
                f"| {NAME[a]} - {NAME[bb]} | {meta[key]['label']}{'*' if meta[key]['aligned'] else ''} | {cmp['n']} | "
                f"{f(cmp['mean_diff'], 4)} [{f(ci[0], 4) if ci else 'N/A'}, {f(ci[1], 4) if ci else 'N/A'}] | "
                f"{f(cmp['median_diff'], 4)} | {cmp['wins']} / {cmp['ties']} / {cmp['losses']} | {f(cmp['effect_dz'], 2)} |"
            )
    w(
        "\nWins/losses count scenarios where the first policy's value is higher/lower; whether that is "
        "better depends on the metric's direction (section 2).\n"
    )

    w("## 4. Pre-declared hypothesis tests (AidOS vs FCFS, exact sign test, Holm-adjusted)\n")
    w("| Metric | Sign-test p | Holm-adjusted p |")
    w("|---|---|---|")
    for t in st["primary_tests"]:
        w(
            f"| {meta[t['metric']]['label']}{'*' if meta[t['metric']]['aligned'] else ''} | {p(t['sign_p'])} | {p(t['holm_p'])} |"
        )
    w("")

    w("## 5. By scenario family: mean per policy\n")
    for key in ["urgency_weighted_coverage", "min_zone_coverage", "starved_share", "jain_fairness"]:
        w(
            f"**{meta[key]['label']}{'*' if meta[key]['aligned'] else ''}** ({meta[key]['better']} is better)\n"
        )
        w("| Family | " + " | ".join(NAME[x] for x in POLICIES) + " | AidOS - FCFS [95% CI] |")
        w("|---|" + "---|" * (len(POLICIES) + 1))
        for fam in st["families"]:
            cells = [f(st["by_family"][fam][pol][key]["mean"]) for pol in POLICIES]
            cmp = next(
                x
                for x in st["comparisons"]
                if (x["scope"], x["a"], x["b"], x["metric"]) == (fam, "aidos", "fcfs", key)
            )
            ci = cmp["ci_mean"]
            name = s["families"][fam]["name"]
            w(
                f"| {fam} {name} | "
                + " | ".join(cells)
                + f" | {f(cmp['mean_diff'])} [{f(ci[0]) if ci else 'N/A'}, {f(ci[1]) if ci else 'N/A'}] |"
            )
        w("")

    dr = s["dynamic_recommendation"]
    w(
        f"## 6. Dynamic, recommendation mode (shared state; {dr['scripts']} scripts, {dr['steps']} steps)\n"
    )
    w(
        "Mean units reallocated versus the previous step, and share of steps where the plan changed:\n"
    )
    w("| Event | " + " | ".join(NAME[x] for x in POLICIES) + " |")
    w("|---|" + "---|" * len(POLICIES))
    for e in dr["event_types"]:
        cells = [
            f"{f(dr['by_event'][e][pol]['reallocated_units']['mean'], 1)} ({f(dr['by_event'][e][pol]['plan_changed']['mean'], 2)})"
            for pol in POLICIES
        ]
        w(f"| {e} | " + " | ".join(cells) + " |")
    w("\nPaired by script (mean over each script's steps):\n")
    w("| Comparison | Metric | n scripts | Mean diff [95% CI] | W / T / L |")
    w("|---|---|---|---|---|")
    for cmp in dr["comparisons"]:
        if (cmp["a"], cmp["b"]) in (("aidos", "fcfs"), ("aidos_balanced", "aidos")):
            ci = cmp["ci_mean"]
            w(
                f"| {NAME[cmp['a']]} - {NAME[cmp['b']]} | {cmp['metric']} | {cmp['n']} | {f(cmp['mean_diff'], 3)} "
                f"[{f(ci[0], 3) if ci else 'N/A'}, {f(ci[1], 3) if ci else 'N/A'}] | {cmp['wins']} / {cmp['ties']} / {cmp['losses']} |"
            )
    w("")

    dd = s["dynamic_dispatch"]
    w(f"## 7. Dynamic, dispatch mode (each policy's own trajectory; {dd['scripts']} scripts)\n")
    w("| Metric | " + " | ".join(NAME[x] for x in POLICIES) + " |")
    w("|---|" + "---|" * len(POLICIES))
    for key in [
        "dispatched_units",
        "fulfilment",
        "urgency_weighted_fulfilment",
        "min_zone_fulfilment",
        "zones_never_served",
    ]:
        digits = 1 if key in ("dispatched_units", "zones_never_served") else 3
        w(
            f"| {key} | "
            + " | ".join(f(dd["overall"][pol][key]["mean"], digits) for pol in POLICIES)
            + " |"
        )
    w("\nIntegrity (runs passing / runs):\n")
    w(
        "| Policy | Inventory conserved | Ledger consistent | Double dispatch blocked | Rejected script events |"
    )
    w("|---|---|---|---|---|")
    for pol in POLICIES:
        i = dd["integrity"][pol]
        w(
            f"| {NAME[pol]} | {i['inventory_conserved']}/{i['runs']} | {i['ledger_consistent']}/{i['runs']} | "
            f"{i['double_dispatch_blocked']}/{i['runs']} | {i['rejected_events']} |"
        )
    w("\nPaired by script:\n")
    w("| Comparison | Metric | n | Mean diff [95% CI] | W / T / L |")
    w("|---|---|---|---|---|")
    for cmp in dd["comparisons"]:
        if (cmp["a"], cmp["b"]) in (("aidos", "fcfs"), ("aidos_balanced", "aidos")):
            ci = cmp["ci_mean"]
            w(
                f"| {NAME[cmp['a']]} - {NAME[cmp['b']]} | {cmp['metric']} | {cmp['n']} | {f(cmp['mean_diff'], 3)} "
                f"[{f(ci[0], 3) if ci else 'N/A'}, {f(ci[1], 3) if ci else 'N/A'}] | {cmp['wins']} / {cmp['ties']} / {cmp['losses']} |"
            )
    w("")

    w("## 8. Decomposition: the late, urgent zone in the dynamic scripts\n")
    w(
        "Every dynamic script adds a new zone that arrives after all others with high ratings (6-10). "
        "These tables separate its effect from the original zones.\n"
    )
    rec = list(csv.DictReader((run / "dynamic_recommendation.csv").open(encoding="utf-8")))
    w(
        "| Recommendation mode: mean starved zones per step | "
        + " | ".join(NAME[x] for x in POLICIES)
        + " |"
    )
    w("|---|" + "---|" * len(POLICIES))
    for label, cond in (
        ("Step 1 (before the new zone)", lambda r: int(r["step"]) == 1),
        ("Steps 2-7 (new zone present)", lambda r: int(r["step"]) > 1),
    ):
        cells = []
        for pol in POLICIES:
            v = [float(r["starved_zones_after"]) for r in rec if r["policy"] == pol and cond(r)]
            cells.append(f(sum(v) / len(v)) if v else "N/A")
        w(f"| {label} | " + " | ".join(cells) + " |")
    zones = list(csv.DictReader((run / "dispatch_zones.csv").open(encoding="utf-8")))
    w(
        "\n| Dispatch mode: zones never served (all scripts) | "
        + " | ".join(NAME[x] for x in POLICIES)
        + " |"
    )
    w("|---|" + "---|" * len(POLICIES))
    for label, new in (("The late new zone", True), ("Original zones", False)):
        cells = [
            str(
                sum(
                    1
                    for r in zones
                    if r["policy"] == pol
                    and r["zone_id"].startswith("zone-new") == new
                    and float(r["total_need"]) > 0
                    and float(r["dispatched"]) == 0
                )
            )
            for pol in POLICIES
        ]
        w(f"| {label} | " + " | ".join(cells) + " |")
    w("")

    w("## 9. Runtime scaling (median ms; one machine)\n")
    sizes = sorted({pt["zones"] for pt in s["scaling"]["points"]})
    w("| Zones | " + " | ".join(NAME[x] for x in POLICIES) + " | AidOS variables (median) |")
    w("|---|" + "---|" * (len(POLICIES) + 1))
    for n in sizes:
        pts = {pt["policy"]: pt for pt in s["scaling"]["points"] if pt["zones"] == n}
        w(
            f"| {n} | "
            + " | ".join(f(pts[pol]["runtime_ms"]["median"], 2) for pol in POLICIES)
            + f" | {f(pts['aidos']['variables']['median'], 0)} |"
        )
    w("")
    args.out.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
